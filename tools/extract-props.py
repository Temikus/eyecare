#!/usr/bin/env python3
"""Generate Sources/PWMKit/Catalog.swift from IOMFB runtime-property names in a kernelcache.

The `iomfb_RuntimeProperty_<name>` strings in IOMobileGraphicsFamily are the set of keys the
AppleCLCD2 node accepts; the bare `<name>` is the IORegistry key. Passing --baseline (the
pre-update cache) tags keys that the current OS added.

Output is line-wrapped by `swift format`, which `just regen-catalog` runs afterwards.

Per-kext attribution is deliberately not attempted: kext segment ranges overlap inside a kernel
collection, so mapping a string offset back to one kext gives wrong answers.
"""

from __future__ import annotations

import argparse
import datetime
import re
import subprocess
import sys
import tempfile
from pathlib import Path

PROP_RE = re.compile(rb"iomfb_RuntimeProperty_([A-Za-z0-9_]{2,64})")
VERSION_RE = re.compile(rb"Darwin Kernel Version ([0-9]+\.[0-9]+\.[0-9]+)")

# First match wins.
CATEGORIES: list[tuple[str, str]] = [
    ("dimming", r"BLM|Dimming|Nits|DBV|HBLD|PixelBacklightModulation|uniformity2D|enableDither"
                r"|[Bb]rightness|BLNitsCap|limit_max_physical|RTPLC|ALSS|AmbientLight|Sloper"
                r"|Pulse|Width|Modulat|Flicker|Duty|LED"),
    ("refresh", r"^enableRR|RRBP|Regamma|NESR|VRR|GenLock|genLock|Frame[Rr]ate|QMS|LFC|RTR"),
    ("color", r"PCC|APT|[Gg]amma|CLUT|Colour|Color|CSC|EDR|AppleLook|Calibration|calibration"
              r"|Tone|Contrast|GCP|Degamma"),
    ("thermal", r"IRDC|PTUC|Temp|temperature|Thermal"),
    ("power", r"Idle|Powergate|PowerGate|Sleep|Standby|AOD|AOT|Assertion"),
]

# Keys that drive panel brightness registers directly: a bad value can leave the panel dark.
RISKY = re.compile(r"^DBV|^BLMVLEDManual$|^brightnessLevel|^limit_max_physical_brightness$"
                   r"|^BLNitsCap$|^digitalDimmingLevel$")

# IOMFB stores these as 16.16 fixed point (65536 == 1.0).
FIXED_POINT = re.compile(r"Nits|Dimming|[Bb]rightness|Correction|Factor|Scaler")


def load(path: Path) -> bytes:
    """Read a kernelcache, decompressing it first when handed a raw IMG4."""
    data = path.read_bytes()
    if b"IMG4" not in data[:64] and b"IM4P" not in data[:64]:
        return data
    script = Path(__file__).with_name("extract-kernelcache.sh")
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "kc.bin"
        subprocess.run([str(script), str(path), str(out)], check=True, stdout=subprocess.DEVNULL)
        return out.read_bytes()


def properties(data: bytes) -> set[str]:
    return {m.group(1).decode() for m in PROP_RE.finditer(data)}


def kernel_version(data: bytes) -> str:
    m = VERSION_RE.search(data)
    return m.group(1).decode() if m else "unknown"


def categorise(key: str) -> str:
    for name, pattern in CATEGORIES:
        if re.search(pattern, key):
            return name
    return "other"


def swift_literal(value: str | None) -> str:
    return "nil" if value is None else f'"{value}"'


def render(keys: dict[str, str | None], current: str, baseline: str | None) -> str:
    provenance = f"// Darwin {current}" + (f", diffed against Darwin {baseline}" if baseline else "")
    lines = [
        "// Generated by tools/extract-props.py -- do not edit by hand.",
        f"// Run `just regen-catalog` after a macOS update to refresh it.",
        provenance,
        f"// Generated {datetime.date.today().isoformat()}, {len(keys)} keys.",
        "",
        "extension Catalog {",
        "    public static let entries: [CatalogEntry] = [",
    ]
    for key in sorted(keys, key=str.lower):
        lines.append(
            f'        CatalogEntry(key: "{key}", '
            f"category: .{categorise(key)}, "
            f"risk: .{'risky' if RISKY.search(key) else 'safe'}, "
            f"fixedPoint: {'true' if FIXED_POINT.search(key) else 'false'}, "
            f"newIn: {swift_literal(keys[key])}),"
        )
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--current", type=Path, required=True,
                    help="decompressed (or IMG4) kernelcache for the running OS")
    ap.add_argument("--baseline", type=Path,
                    help="pre-update kernelcache; keys absent from it are tagged as new")
    ap.add_argument("--new-in", dest="new_in",
                    help="label for keys new in --current, e.g. 27 (default: its Darwin major)")
    ap.add_argument("--out", type=Path, default=Path("Sources/PWMKit/Catalog.swift"))
    args = ap.parse_args()

    current = load(args.current)
    current_keys = properties(current)
    if not current_keys:
        print(f"no iomfb_RuntimeProperty_* strings in {args.current}", file=sys.stderr)
        return 1
    current_version = kernel_version(current)

    baseline_version: str | None = None
    added: set[str] = set()
    if args.baseline:
        baseline = load(args.baseline)
        baseline_version = kernel_version(baseline)
        baseline_keys = properties(baseline)
        added = current_keys - baseline_keys
        removed = baseline_keys - current_keys
        print(f"baseline Darwin {baseline_version}: {len(baseline_keys)} keys", file=sys.stderr)
        print(f"removed since baseline: {', '.join(sorted(removed)) or 'none'}", file=sys.stderr)

    label = args.new_in or current_version.split(".")[0]
    keys = {key: (label if key in added else None) for key in current_keys}

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(keys, current_version, baseline_version))
    print(f"current Darwin {current_version}: {len(keys)} keys, {len(added)} new -> {args.out}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
